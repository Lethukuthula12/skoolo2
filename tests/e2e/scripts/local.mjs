import { spawnSync } from 'node:child_process';
import { mkdir, readFile, writeFile, copyFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import pg from 'pg';
import { API_URL, DB_URL, LOCAL_PROJECT, assertLocalApi, assertLocalDatabase, assertLocalProject } from './local-safety.mjs';
import { seed } from './seed.mjs';

export const project = fileURLToPath(new URL('../', import.meta.url));
const root = path.resolve(project, '../..');
const local = path.join(project, '.local');
const binary = path.join(project, 'node_modules/supabase/dist/supabase.js');
const command = process.argv[2] || 'doctor';
function run(bin, args, capture = false) {
  const result = spawnSync(bin, args, { cwd: project, encoding: 'utf8', stdio: capture ? 'pipe' : 'inherit', windowsHide: true });
  if (result.error || result.status !== 0) throw new Error(`${path.basename(bin)} failed. ${result.error?.message || (capture ? result.stderr : 'See output above.')}`);
  return result.stdout;
}
function cli(args, capture = false) { return run(process.execPath, [binary, '--workdir', local, '--yes', ...args], capture); }
async function configure() {
  const config = await readFile(path.join(project, 'local.supabase.toml'), 'utf8');
  assertLocalProject(config);
  await mkdir(path.join(local, 'supabase/migrations'), { recursive: true });
  await writeFile(path.join(local, 'supabase/config.toml'), config);
  for (const name of await readdir(path.join(root, 'supabase/migrations'))) {
    if (name.endsWith('.sql')) await copyFile(path.join(root, 'supabase/migrations', name), path.join(local, 'supabase/migrations', name));
  }
}
async function status() {
  await readFile(path.join(local, 'supabase/config.toml'), 'utf8').then(assertLocalProject);
  const output = cli(['status', '--output', 'json'], true);
  const data = JSON.parse(output);
  assertLocalApi(data.API_URL);
  assertLocalDatabase(data.DB_URL);
  if (!data.ANON_KEY || !data.SERVICE_ROLE_KEY) throw new Error('Local Supabase did not return its development keys.');
  return data;
}
async function doctor() {
  const [major, minor] = process.versions.node.split('.').map(Number);
  if (major !== 22 || minor < 18) throw new Error('Install Node 22.18 or newer in the Node 22 line before running test setup.');
  console.log(`Node ${process.version}; test tooling requires Node 22.18+ (see .node-version).`);
  run('git', ['--version']);
  run('docker', ['version', '--format', '{{.Server.Version}}']);
  run(process.execPath, [binary, '--version']);
  console.log('Prerequisites available. Run npm run local:setup from the repository root.');
}
async function reset() {
  await status(); // fail closed before any destructive command
  console.log('Resetting ONLY the dedicated skoolo-e2e local Docker database and its fictional data.');
  cli(['db', 'reset', '--local', '--no-seed']);
  const data = await status();
  await seed(data);
  const browser = { apiUrl: API_URL, anonKey: data.ANON_KEY };
  await writeFile(path.join(local, 'browser.json'), JSON.stringify(browser, null, 2) + '\n');
  await writeFile(path.join(root, 'web/projects/shared/src/lib/environment.local.ts'),
    `// Generated by npm run local:setup. Ignored by Git. Local test values only.\nexport const supabaseEnvironment = ${JSON.stringify({ url: API_URL, anonKey: data.ANON_KEY }, null, 2)} as const;\nexport const turnstileSiteKey = '1x00000000000000000000AA';\nexport const parentAppUrl = 'http://localhost:4400';\n`);
  console.log('Local setup ready. Run npm run local:start. Test accounts: docs/testing/new-laptop.md');
}
async function rls() {
  await status();
  const client = new pg.Client({ connectionString: DB_URL });
  await client.connect();
  try {
    for (const name of ['tenant_isolation.sql', 'rls_coverage.sql']) {
      const sql = await readFile(path.join(root, 'supabase/tests', name), 'utf8');
      try { await client.query(sql); throw new Error(`${name}: missing completion sentinel`); }
      catch (error) {
        await client.query('ROLLBACK');
        if (!String(error.message).includes('SKOOLO_RLS_TESTS_PASSED')) throw error;
        console.log(`${name}: ${error.message}`);
      }
    }
  } finally { await client.end(); }
}
try {
  if (command === 'doctor') await doctor();
  else if (command === 'setup') { await doctor(); await configure(); cli(['start']); await reset(); }
  else if (command === 'reset') { await configure(); await reset(); }
  else if (command === 'stop') {
    await readFile(path.join(local, 'supabase/config.toml'), 'utf8').then(assertLocalProject);
    cli(['stop']); console.log(`${LOCAL_PROJECT} stopped; Docker volumes retained.`);
  } else if (command === 'rls') await rls();
  else throw new Error(`Unknown command: ${command}`);
} catch (error) { console.error(error.message); process.exitCode = 1; }
